"""
    nested_subset_indices(n, fractions; seed=DEFAULT_SEED) -> Vector{Vector{Int}}

Return, for each fraction in call order, the sorted indices of a random subset of
`1:n` holding `round(Int, fraction * n)` transactions. Every subset is a prefix of
one seeded permutation, so a smaller subset lies inside every larger one and a size
change never swaps in other transactions. Sorting keeps the database order in each
subset. Throws `ArgumentError` for a fraction outside (0, 1], repeated fractions, or
a fraction that keeps no transaction.
"""
function nested_subset_indices(n::Integer, fractions::AbstractVector{<:Real}; seed::Integer=DEFAULT_SEED)
    allunique(fractions) || throw(ArgumentError("subset fractions must be distinct, got $fractions"))
    for fraction in fractions
        0 < fraction <= 1 || throw(ArgumentError("subset fraction must be in (0, 1], got $fraction"))
        round(Int, fraction * n) > 0 ||
            throw(ArgumentError("subset fraction $fraction of $n transactions keeps no transaction"))
    end
    order = randperm(Xoshiro(seed), n)
    return [sort!(order[1:round(Int, fraction * n)]) for fraction in fractions]
end

"""Name a subset by its base dataset and percentage, such as `accidents-p10`."""
function subset_name(base::AbstractString, fraction::Real)
    percent = 100 * fraction
    return "$base-p" * (isinteger(percent) ? string(Int(percent)) : string(percent))
end

"""
    prepare_subsets(base, source, dir, fractions; seed=DEFAULT_SEED, recorded=nothing)
        -> Vector{DatasetEntry}

Write one SPMF file per fraction of the verified database at `source` into `dir`,
named by `subset_name`, and return entries with their SHA-256 and statistics. An
entry has no download source, because the subset is regenerated from `base`.
With `recorded`, a manifest from an earlier run, every subset must reproduce its
recorded SHA-256; a mismatch throws `ArgumentError` naming the subset, so a changed
seed, base file, or writer cannot silently replace the measured inputs.
"""
function prepare_subsets(base::DatasetEntry, source::AbstractString, dir::AbstractString,
                         fractions::AbstractVector{<:Real}; seed::Integer=DEFAULT_SEED,
                         recorded::Union{Nothing,AbstractDict{String,DatasetEntry}}=nothing)
    file_sha256(source) == base.sha256 ||
        throw(ArgumentError("dataset $(base.name): $source does not have the manifest SHA-256"))
    transactions = read_transactions(source)
    entries = DatasetEntry[]
    for (fraction, kept) in zip(fractions, nested_subset_indices(length(transactions), fractions; seed))
        name = subset_name(base.name, fraction)
        subset = transactions[kept]
        path = joinpath(dir, name * ".txt")
        write_transactions(path, subset)
        entry = DatasetEntry(; name, file=basename(path), sha256=file_sha256(path),
            version="seed $seed nested subset, fraction $fraction, of $(base.name) sha256 $(base.sha256)",
            sources=DatasetSource[], stats=dataset_stats(subset))
        if recorded !== nothing && haskey(recorded, name) && recorded[name].sha256 != entry.sha256
            throw(ArgumentError("subset $name has SHA-256 $(entry.sha256), but the manifest records " *
                                "$(recorded[name].sha256)"))
        end
        push!(entries, entry)
    end
    return entries
end

"""Write `entries` as a manifest that `load_manifest` reads back."""
function write_subset_manifest(path::AbstractString, entries::AbstractVector{DatasetEntry})
    table = Dict{String,Any}()
    for entry in entries
        stats = entry.stats
        table[entry.name] = Dict{String,Any}("version" => entry.version, "file" => entry.file,
            "sha256" => entry.sha256, "sources" => Any[],
            (key => getfield(stats, Symbol(key)) for key in STAT_KEYS)...)
    end
    open(path, "w") do io
        println(io, "# Generated by experiments/prepare_subsets.jl; the SHA-256 values make a rerun verifiable.\n")
        TOML.print(io, table; sorted=true)
    end
    return path
end
